-- 016 — 유튜브 댓글을 질문으로, 그 댓글에 답글. 2026-11-01. (tease §3-5 · §7-5)
--
-- 질문의 출처가 셋이 된다: 우리 페이지(page) · 라이브 채팅 다시보기(live_chat) · 유튜브 댓글(comment).
-- 댓글 질문에 숏폼이 생기면 크리에이터가 그 댓글에 답글을 단다 — 루프가 유튜브 안에서 닫힌다.

-- ============================================================
-- questions — 댓글에서 온 질문
-- ============================================================
-- external_id = 최상위 댓글 id. 🔴 답글을 달 부모가 이 id 다(commentThreads 의 topLevelComment.id).
-- asked_at_sec 는 비운다 — 댓글은 영상 안 시각이 없다.
alter table questions drop constraint questions_origin_check;
alter table questions add constraint questions_origin_check
    check (origin in ('page', 'live_chat', 'comment'));

-- ============================================================
-- question_replies — 유튜브 댓글에 단 답글. 한 번이 한 행
-- ============================================================
create table question_replies (
    id                  integer generated by default as identity primary key,
    -- 🔴 on delete **set null**. 질문은 원본을 지우면 함께 사라지는데, 유튜브의 답글은 남는다 — 어디에
    -- 무엇을 달았는지는 이 행이 따로 들고 있다(clip_uploads 와 같은 판단).
    question_id         integer     references questions (id) on delete set null,
    -- 어느 숏폼으로 답했나. 초안의 시각·주소가 이 클립에서 나왔다.
    clip_id             integer     references clips (id) on delete set null,
    -- 답글을 단 부모(최상위 댓글)와 그 영상. 답글 주소(watch?v=…&lc=…)를 짓는 데 둘 다 든다.
    parent_comment_id   text        not null,
    video_id            text        not null,
    -- 실제로 보낸 본문. 크리에이터가 입력란에서 고친 뒤의 것이다.
    text                text        not null check (length(trim(text)) > 0),
    -- POSTING 은 요청이 나가 있는 중. 재기동하면 FAILED 로 정리한다(server.serve) — 실제로는 달렸을 수 있다.
    status              text        not null default 'POSTING'
                                    check (status in ('POSTING', 'DONE', 'FAILED')),
    youtube_comment_id  text,
    -- 답글을 단 채널. 🔴 영상 주인 채널이어야 한다(answers/replies.py 가 달기 직전에 확인한다).
    channel_id          text,
    error               text,
    created_at          timestamptz not null default now(),
    finished_at         timestamptz,
    -- 달렸다고 적었는데 어느 답글인지 모르면 다시 찾을 길이 없다.
    check (status <> 'DONE' or youtube_comment_id is not null)
);
-- 🔴 **같은 댓글에 두 번 달지 않는다.** 화면을 두 번 누르든 질문을 다시 가져와 행이 바뀌든, 부모 댓글이
-- 같으면 막힌다. 실패한 것만 다시 달 수 있다 — 그래서 FAILED 는 빼고 건다.
create unique index uq_question_replies_parent on question_replies (parent_comment_id) where status <> 'FAILED';
create index idx_question_replies_question on question_replies (question_id);

-- ============================================================
-- stage_calls — 가져오기·답글도 단계다(규약: 모든 단계를 기록한다)
-- ============================================================
alter table stage_calls drop constraint stage_calls_stage_check;

alter table stage_calls add constraint stage_calls_stage_check check (stage in
    ('ping', 'chunk', 'stt', 'segment', 'describe', 'overview', 'rank', 'cut', 'render',
     'caption', 'embed', 'retrieve', 'cluster', 'judge', 'classify', 'locate', 'download', 'preview',
     'upload', 'livechat', 'comment', 'reply'));
