-- 019 — 숏폼 편집 P1: 템플릿 · 시리즈 · 클립 편집 명세. 2026-11-05. (tease §5-10 · upgrade_plan §2-19)
--
-- 지금까지 숏폼은 원본을 블러 배경 위에 얹은 한 모양뿐이었다. 원티드 숏폼처럼 시리즈 배지 · 카피 · 영상 칸 · 출처를
-- 쌓은 카드를 만들려고, 모양을 코드에서 빼서 **데이터(templates.spec)** 로 둔다. 검증은 코드(pipeline/templates.py)가 한다 —
-- spec 은 블록 목록이라 CHECK 로 모양을 지킬 수 없다.

-- ============================================================
-- templates — 숏폼 모양
-- ============================================================
create table templates (
    id          integer generated by default as identity primary key,
    name        text    not null unique check (length(trim(name)) > 0),
    -- 계열. 지금은 블록을 위아래로 쌓는 카드뿐이다. 9:16 꽉 채움 · 화면 분할은 보류(tease §5-10).
    kind        text    not null default 'card' check (kind in ('card')),
    spec        jsonb   not null,
    -- 어디서 왔나. 'seed'(이 마이그레이션) · 'manual'(관리자가 만듦, P2) · 'reference'(기존 숏폼 분석, P3)
    origin      text    not null default 'manual' check (origin in ('seed', 'manual', 'reference')),
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);

-- ============================================================
-- series — 채널의 시리즈(왓츠인 마이 AI · 잡소리 …). 배지 이미지와 기본 템플릿을 갖는다
-- ============================================================
create table series (
    id          integer generated by default as identity primary key,
    name        text    not null unique check (length(trim(name)) > 0),
    -- 🔴 work_dir 기준 **상대경로**. null 이면 시리즈 이름을 글자 배지로 그린다.
    badge_path  text,
    template_id integer references templates (id) on delete set null,
    created_at  timestamptz not null default now()
);

-- 🔴 기존 테이블에 붙이는 컬럼에는 CHECK 를 걸지 않는다(tease §6-1). 값 검증은 코드에서.
-- 이 영상이 어느 시리즈인가. 클립 편집 명세의 시리즈 기본값이다.
alter table sources add column series_id integer references series (id) on delete set null;

-- 클립 편집 명세(pipeline/layout.py). null 이면 예전의 블러 렌더 그대로다.
alter table clips add column layout jsonb;
-- 마지막 렌더에 쓴 명세 — 그때의 템플릿 spec 까지 복사해 둔다. 템플릿을 나중에 고쳐도 이 영상이 무엇으로
-- 만들어졌는지 남고, layout 과 다르면 "다시 렌더해야 한다" 를 화면이 안다.
alter table clips add column render_spec jsonb;

