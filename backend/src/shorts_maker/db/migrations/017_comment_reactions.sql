-- 017 — 댓글 두 갈래(질문 · 감상)와 시청자 반응 요약. 2026-11-01. (tease §3-5 · §3-6)
--
-- 삼성(원본 4) 댓글 28개에 채팅 규칙을 그대로 대자 12개가 질문으로 들어왔는데 거의 전부 감상이었다.
-- 감상은 질문이 아니지만 "이 회차가 어떻게 받아들여졌나" 를 말하는 리뷰 데이터다 — 리포트로 보낸다.

-- ============================================================
-- source_comments — 받은 최상위 댓글 전부. 갈래를 함께
-- ============================================================
create table source_comments (
    id              integer generated by default as identity primary key,
    source_id       integer     not null references sources (id) on delete cascade,
    -- 유튜브 최상위 댓글 id. 질문이면 questions.external_id 와 같은 값이다.
    comment_id      text        not null,
    -- question = 문장 끝이 물음표·의문형 어미(→ questions 로도 간다), review = 나머지(→ 리포트의 시청자 반응).
    kind            text        not null check (kind in ('question', 'review')),
    text            text        not null check (length(trim(text)) > 0),
    -- 🔴 작성자 이름은 두지 않는다. 채널 id 의 해시뿐이다(livechat.viewer_id).
    viewer_id       text        not null,
    published_at    timestamptz,
    -- 마지막으로 받은 때. 🔴 개발자 정책 III.E.4 — 30일 안에 갱신하거나 지운다(upgrade_plan §2-17 TODO).
    fetched_at      timestamptz not null default now(),
    -- 몇 번 가져와도 한 줄. 다시 가져오면 본문·갈래를 갱신한다.
    unique (source_id, comment_id)
);

-- ============================================================
-- reaction_summaries — 감상 댓글 AI 요약. 한 번이 한 행, 리포트는 최신 것
-- ============================================================
create table reaction_summaries (
    id              integer generated by default as identity primary key,
    source_id       integer     not null references sources (id) on delete cascade,
    -- 요약할 때 본 감상 수. 지금 수와 다르면 화면이 "요약 뒤 댓글이 바뀌었다" 를 띄운다.
    reviews         integer     not null check (reviews > 0),
    -- {overview, themes: [{kind, title, detail, comments: [댓글 id …]}]}. 근거는 검증을 거친 것만 남는다.
    body            jsonb       not null,
    -- 그때 쓴 요약 관점(프롬프트 화면). 나중에 관점을 바꿔도 이 요약이 무엇으로 나왔는지 남는다.
    guide           text,
    created_at      timestamptz not null default now()
);
create index idx_reaction_summaries_source on reaction_summaries (source_id, id);

-- ============================================================
-- admin_standards — 프롬프트 화면에서 고치는 글이 둘이 된다
-- ============================================================
-- standard = 관리자 기준(클립 선호, 순위·자르기·후보·판정 점수), reaction = 시청자 반응 요약 관점.
-- 🔴 둘은 섞이지 않는다. 기준은 요약에, 관점은 클립에 들어가지 않는다(tests/test_standards.py).
alter table admin_standards add column kind text not null default 'standard'
    check (kind in ('standard', 'reaction'));
create index idx_admin_standards_kind on admin_standards (kind, id);

