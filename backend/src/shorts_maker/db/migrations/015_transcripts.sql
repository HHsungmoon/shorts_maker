-- 015 — 두 대사 보관. 2026-11-01. (tease §5-1 · §6-2)
--
-- 대사는 유튜브 자막이 기본이고 음성 인식은 선택이다. 둘을 **따로 저장**해 맞대 볼 수 있게 하고,
-- utterances 는 그중 **지금 쓰는 것**을 청크별로 담는 자리로 남는다(뒤 단계는 바뀌지 않는다).

-- ============================================================
-- transcripts — 받은 대사 그대로
-- ============================================================
-- 🔴 청크가 아니라 **원본**에 매단다. 분석 범위를 다시 추출하면 청크가 지워지는데(cascade), 몇십 분 걸린
-- 음성 인식이 그때 같이 사라지면 안 된다. 시각은 원본 절대 초.
create table transcripts (
    id              integer     generated by default as identity primary key,
    source_id       integer     not null references sources(id) on delete cascade,
    origin          text        not null check (origin in ('youtube', 'whisper')),
    start_sec       double precision not null,
    end_sec         double precision not null,
    text            text        not null,
    words           jsonb,
    avg_logprob     double precision,
    no_speech_prob  double precision,
    created_at      timestamptz not null default now(),
    check (end_sec > start_sec)
);
create index idx_transcripts_source on transcripts (source_id, origin, start_sec);

-- ============================================================
-- stt_spans — 음성 인식이 들은 오디오 범위
-- ============================================================
-- 🔴 **한 번 들은 초는 다시 듣지 않는다**(사용자 결정 2026-11-01). 31분에 20분·메모리 4GB 를 쓰는 일이고 같은
-- 모델·같은 오디오면 결과가 바뀔 이유가 없다. [음성 인식] 은 여기 없는 범위만 돈다.
-- 무음이라 발화가 하나도 없는 범위도 "들었다" 이므로 transcripts 만으로는 알 수 없다 — 그래서 따로 둔다.
create table stt_spans (
    id              integer     generated by default as identity primary key,
    source_id       integer     not null references sources(id) on delete cascade,
    start_sec       double precision not null check (start_sec >= 0),
    end_sec         double precision not null,
    model           text        not null,
    language        text,
    initial_prompt  text,
    created_at      timestamptz not null default now(),
    check (end_sec > start_sec)
);
create index idx_stt_spans_source on stt_spans (source_id, start_sec);

-- ============================================================
-- 지금까지의 대사 옮겨 담기
-- ============================================================
-- 이 마이그레이션 전의 발화는 전부 음성 인식이다(자막 경로는 이 마이그레이션과 함께 생겼다).
insert into transcripts (source_id, origin, start_sec, end_sec, text, words, avg_logprob, no_speech_prob, created_at)
select c.source_id, 'whisper', u.start_sec, u.end_sec, u.text, u.words, u.avg_logprob, u.no_speech_prob, u.created_at
from utterances u
join chunks c on c.id = u.chunk_id;

-- 발화가 있는 청크 = 음성 인식이 들은 범위. 모델은 그 원본의 마지막 성공한 stt 호출에서.
insert into stt_spans (source_id, start_sec, end_sec, model, language, created_at)
select c.source_id, c.start_sec, c.end_sec,
       coalesce(
           (select sc.model from stage_calls sc
             where sc.source_id = c.source_id and sc.stage = 'stt' and sc.error is null
             order by sc.id desc limit 1),
           'faster-whisper'),
       s.language,
       min(u.created_at)
from chunks c
join sources s on s.id = c.source_id
join utterances u on u.chunk_id = c.id
group by c.id, c.source_id, c.start_sec, c.end_sec, s.language;

update sources s set caption_source = 'whisper'
where caption_source is null
  and exists (select 1 from chunks c join utterances u on u.chunk_id = c.id where c.source_id = s.id);
