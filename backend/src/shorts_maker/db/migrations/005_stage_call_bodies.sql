-- 005 — 단계 기록에 프롬프트와 원본 응답. 2026-09-09.
--
-- 🔴 **왜 필요한가.** `stage_calls` 는 모델·토큰·지연·판단 근거(params)까지 남기는데
-- **모델이 실제로 무엇을 보고 무엇을 답했는지**는 안 남았다. 그래서 판정이 이상해 보일 때
-- 확인할 방법이 "같은 호출을 다시 하는 것" 뿐이었다. 2026-09-09 에 그걸 두 번 했다 —
-- 구간 검색이 왜 답을 놓치는지 알아내는 데 임시 스크립트로 호출을 재현해야 했다.
-- 무료 등급은 하루 수십 회라 그 재현 자체가 할당량을 깎는다.
--
-- Langfuse 같은 LLM 관측 도구를 붙이는 것도 검토했다가 물렀다. 비용·지연·토큰은 이미 이 표가
-- 정본으로 갖고 있어서 **정본이 두 곳**이 되고, 프롬프트에는 원본 영상의 대사가 통째로 들어가
-- 채널 사용 허락이 걸린 콘텐츠를 제3자에 넘기는 문제가 생긴다. 게다가 이 파이프라인은 분기하는
-- 에이전트가 아니라 고정 DAG 라(답변당 호출 5개) 추적 트리가 이 표의 5행보다 더 알려주는 게 적다.
-- 빠진 것은 본문 둘뿐이었고, 그래서 컬럼 둘을 더한다.
--
-- 크기: 실측으로 답변 하나가 프롬프트 약 20KB(구간 선택 2KB + rank 12KB + judge 3×2KB)다.
-- 응답은 출력 토큰이 수백이라 훨씬 작다. Postgres 는 text 를 TOAST 로 압축해 저장하므로
-- 이 규모에서 상한을 두지 않는다. 끄고 싶으면 `SHORTS_STORE_PROMPTS=0` 이다.

alter table stage_calls add column prompt   text;
alter table stage_calls add column response text;

-- 🔴 목록 조회에서 본문을 **빼고** 읽어야 한다. `select *` 로 읽으면 화면 한 번에 수 MB 가 실린다.
-- 본문은 사용자가 그 행을 펼칠 때만 따로 읽는다(`GET /api/stage-calls/{id}`).
-- 지난 기록에는 값이 없다 — 이 컬럼이 생긴 뒤의 호출부터 쌓인다.
