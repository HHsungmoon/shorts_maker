-- 013 — 유튜브 채널 연결과 Shorts 업로드. 2026-10-31. (tease §7-5)
--
-- 첫 공식 API 기능이다. 스튜디오에서 클립마다 [유튜브에 올리기] 를 누르면 연결된 채널에 올라간다.
--
-- 자격 증명은 둘로 갈린다. 앱의 것(OAuth 클라이언트 ID·시크릿)은 .env 에, **채널의 것**(refresh token)은
-- 여기에 둔다. 채널은 [채널 연결] 을 누를 때 생기고 바뀐다 — 개발은 운영자 개인 채널, 나중에는 원티드.

-- ============================================================
-- youtube_channel — 연결된 채널. 운영자 1명이 쓰는 도구라 한 행이다
-- ============================================================
-- 🔴 id 를 1 로 묶는다. 두 채널이 동시에 연결돼 있으면 "어디로 올라가나" 가 화면마다 달라진다.
-- 다른 채널을 연결하면 이 행을 덮어쓴다(upsert).
create table youtube_channel (
    id              smallint    primary key default 1 check (id = 1),
    -- 🔴 **비밀이다.** 이 값만 있으면 그 채널에 영상을 올릴 수 있다. 어떤 API 응답에도 싣지 않는다
    -- (tests/http 가 응답 본문을 훑어 확인한다). 개발자 정책 III.E.4.a 는 토큰 보관을 허락하지만
    -- 동의한 목적(업로드)에만 쓴다.
    refresh_token   text        not null,
    -- 실제로 받은 범위. 동의 화면에서 사용자가 체크를 풀 수 있어 요청한 것과 다를 수 있다.
    scopes          text        not null,
    -- 채널 id·이름은 **첫 업로드 뒤에** 채운다. youtube.upload 범위로는 channels.list 를 부를 수 없고,
    -- 업로드 응답(snippet.channelId · channelTitle)이 알려 준다. 범위를 늘리지 않으려는 것이다(III.D.2).
    channel_id      text,
    channel_title   text,
    connected_at    timestamptz not null default now()
);

-- ============================================================
-- clip_uploads — 업로드 한 번이 한 행. 같은 클립을 여러 번 올릴 수 있다
-- ============================================================
-- 비공개로 시험한 뒤 공개로 다시 올리는 경우가 있어 클립당 하나로 묶지 않는다.
create table clip_uploads (
    id                  integer generated by default as identity primary key,
    -- 🔴 on delete **set null**. 클립은 "다시 추출" 로 통째로 지워지는데, 그때 이 행까지 사라지면
    -- 유튜브에 올라가 있는 영상의 기록을 잃는다 — 영상은 채널에 남아 있다. 그래서 제목과 영상 id 를
    -- 이 행이 따로 들고 있다.
    clip_id             integer     references clips (id) on delete set null,
    -- 실제로 보낸 값. 크리에이터가 대화상자에서 고친 뒤의 것이다.
    title               text        not null,
    privacy             text        not null check (privacy in ('private', 'unlisted', 'public')),
    -- UPLOADING 은 잡이 도는 중. 워커는 메모리에만 있어 재기동하면 FAILED 로 정리한다(server.serve).
    status              text        not null default 'UPLOADING'
                                    check (status in ('UPLOADING', 'DONE', 'FAILED')),
    youtube_video_id    text,
    channel_id          text,
    error               text,
    created_at          timestamptz not null default now(),
    finished_at         timestamptz,
    -- 올라갔다고 적었는데 어디인지 모르면 그 영상을 다시 찾을 길이 없다.
    check (status <> 'DONE' or youtube_video_id is not null)
);
create index idx_clip_uploads_clip on clip_uploads (clip_id);

-- ============================================================
-- stage_calls — 업로드도 단계다(규약: 모든 단계를 기록한다)
-- ============================================================
-- LLM 이 아니라 model·토큰은 null 이다. 남기는 건 시간이다 — 이 파이프라인의 실제 제약이 시간이고,
-- 클립 하나를 올리는 데 몇 초가 드는지는 여기 말고는 아무 데도 안 남는다.
alter table stage_calls drop constraint stage_calls_stage_check;

alter table stage_calls add constraint stage_calls_stage_check check (stage in
    ('ping', 'chunk', 'stt', 'segment', 'describe', 'overview', 'rank', 'cut', 'render',
     'caption', 'embed', 'retrieve', 'cluster', 'judge', 'classify', 'locate', 'download', 'preview',
     'upload'));
