-- 023 — 관리자 숏폼의 컨셉 셋과 AI 추천 (tease §5-11, 2026-11-08)
--
-- 관리자가 새 클립 탭에서 만드는 숏폼은 브랜딩 · 바이럴 · 정보성 중 하나를 노린다(`pipeline/concepts.py`).
-- 컨셉은 기준 경로의 run 에 붙는다 — 그 run 의 고르기 · 자르기 · AI 카피가 같은 컨셉을 읽는다.
-- null 은 컨셉 이전의 run 과 질문 경로다.
--
-- 🔴 값은 concepts.KEYS 와 같아야 한다(tests/pipeline/test_concepts.py). 컨셉을 늘리면 새 번호로 CHECK 를 바꾼다.

alter table runs add column concept text
    check (concept is null or concept in ('brand', 'viral', 'info'));

-- AI 추천(`pipeline/ideas.py`) — 영상을 읽고 컨셉마다 적합도와 숏폼 주제를 낸 것. 누를 때마다 한 행을 덧붙이고
-- 화면은 최신 행을 본다. 주제가 가리키는 구간은 result 안에 id 와 번호로 남는다 — 구간을 다시 나누면 그 id 가
-- 사라지고, 화면이 "오래된 추천" 으로 알린다(외래키를 걸 수 없는 jsonb 라 읽을 때 맞대 본다).
create table source_ideas (
    id          integer generated by default as identity primary key,
    source_id   integer not null references sources (id) on delete cascade,
    -- 🔴 실제로 보낸 프롬프트 전문(runs.prompt 와 같은 이유 — 글을 고치면 추천끼리 비교가 무의미해진다)
    prompt      text,
    -- {concepts: [{concept, fit, note}], ideas: [{concept, title, segment_id, segment_idx, criteria, reason}], dropped}
    result      jsonb   not null,
    created_at  timestamptz not null default now()
);
create index idx_source_ideas_source on source_ideas (source_id);

alter table stage_calls drop constraint stage_calls_stage_check;

alter table stage_calls add constraint stage_calls_stage_check check (stage in
    ('ping', 'chunk', 'stt', 'segment', 'describe', 'overview', 'rank', 'cut', 'render',
     'caption', 'embed', 'retrieve', 'cluster', 'judge', 'classify', 'locate', 'download', 'preview',
     'upload', 'livechat', 'comment', 'reply', 'reaction', 'analytics', 'scenes', 'focus', 'copy', 'idea'));
